"""Fetch the OMOP CDM 5.4 Postgres DDL and turn it into labpipe migrations.

Downloads the four official DDL files from a pinned OHDSI CommonDataModel tag and
writes them to db/migrations/ with three edits:

1. The @cdmDatabaseSchema placeholder becomes the `cdm` schema.
2. Every foreign key becomes DEFERRABLE INITIALLY DEFERRED, so a load can insert
   rows in any order and the keys are checked once, at commit.
3. The primary key the official files leave out on `vocabulary` is added.

Rerunning the script produces byte-identical files.

Usage: uv run python scripts/fetch_omop_ddl.py
"""

import re
import sys
import urllib.request
from pathlib import Path

TAG = "v5.4.3"
BASE_URL = (
    "https://raw.githubusercontent.com/OHDSI/CommonDataModel/"
    f"{TAG}/inst/ddl/5.4/postgresql/OMOPCDM_postgresql_5.4_{{part}}.sql"
)
OUT_DIR = Path(__file__).resolve().parent.parent / "db" / "migrations"

# Official file part -> migration file name. The order matters: tables, then
# primary keys, then foreign keys (which need the primary keys), then indexes.
PARTS = {
    "ddl": "0100_cdm_tables.sql",
    "primary_keys": "0110_cdm_primary_keys.sql",
    "constraints": "0120_cdm_foreign_keys.sql",
    "indices": "0130_cdm_indexes.sql",
}

# Lines appended to a part to fix gaps in the official files.
# The v5.4.3 primary key file has no key on vocabulary, but two foreign keys
# reference vocabulary(vocabulary_id), and Postgres refuses those without one.
EXTRA = {
    "primary_keys": [
        "-- Added by scripts/fetch_omop_ddl.py: missing from the official file.",
        "ALTER TABLE cdm.vocabulary  ADD CONSTRAINT xpk_vocabulary PRIMARY KEY (vocabulary_id);",
    ],
}

FK_LINE = re.compile(r"^(ALTER TABLE .* FOREIGN KEY .* REFERENCES .*\));\s*$")


def fetch(part: str) -> str:
    with urllib.request.urlopen(BASE_URL.format(part=part), timeout=30) as response:
        return response.read().decode("utf-8")


def transform(part: str, sql: str) -> str:
    sql = sql.replace("\r\n", "\n").replace("@cdmDatabaseSchema", "cdm")

    lines = []
    for line in sql.split("\n"):
        line = line.rstrip()  # keeps pre-commit's whitespace fixer from editing the output
        match = FK_LINE.match(line) if part == "constraints" else None
        lines.append(f"{match.group(1)} DEFERRABLE INITIALLY DEFERRED;" if match else line)
    sql = "\n".join(lines).strip() + "\n" + "\n".join(EXTRA.get(part, []))

    header = (
        f"-- OMOP CDM 5.4 ({part}) from OHDSI/CommonDataModel {TAG}.\n"
        "-- Generated by scripts/fetch_omop_ddl.py. Do not edit by hand.\n"
    )
    if part == "ddl":
        header += "\nCREATE SCHEMA cdm;\n"
    return header + "\n" + sql.strip() + "\n"


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for part, filename in PARTS.items():
        sql = transform(part, fetch(part))
        (OUT_DIR / filename).write_text(sql, encoding="utf-8")
        print(f"wrote db/migrations/{filename}")

    fk_sql = (OUT_DIR / PARTS["constraints"]).read_text(encoding="utf-8")
    total = fk_sql.count("FOREIGN KEY")
    deferred = fk_sql.count("DEFERRABLE INITIALLY DEFERRED")
    if total == 0 or total != deferred:
        print(f"error: {deferred} of {total} foreign keys made deferrable", file=sys.stderr)
        return 1
    print(f"{total} foreign keys, all deferrable")
    return 0


if __name__ == "__main__":
    sys.exit(main())
